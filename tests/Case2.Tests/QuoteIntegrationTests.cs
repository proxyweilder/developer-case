using System.Net;
using System.Net.Http.Json;
using Case2.Domain;
using Dapper;
namespace Case2.Tests;
public class QuoteIntegrationTests(SqlFixture sql) : IClassFixture<SqlFixture>
{
    private async Task<string> Customer(decimal limit)
    {
        var code = "C-" + Guid.NewGuid().ToString("N")[..16];
        await using var db = await sql.Open();
        await db.ExecuteAsync("INSERT dbo.Cariler VALUES(@code,N'PERAKENDE',@limit,0);", new { code, limit });
        return code;
    }
    [SqlFact]
    public async Task Concurrent_quotes_cannot_both_pass_a_limit_for_one_quote()
    {
        var code = await Customer(100);
        var input = new QuoteInput(code, [new(1, 50m)]);
        var responses = await Task.WhenAll(sql.Client.PostAsJsonAsync("/teklifler", input), sql.Client.PostAsJsonAsync("/teklifler", input));
        Assert.Single(responses, x => x.StatusCode == HttpStatusCode.Created);
        Assert.Single(responses, x => x.StatusCode == HttpStatusCode.Conflict);
        await using var db = await sql.Open();
        Assert.Equal(60m, await db.ExecuteScalarAsync<decimal>("SELECT Bakiye FROM dbo.Cariler WHERE CariKod=@code;", new { code }));
        Assert.Equal(1, await db.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM dbo.Teklifler WHERE CariKod=@code;", new { code }));
    }
    [SqlFact]
    public async Task Confirmation_required_response_does_not_write_and_explicit_confirmation_saves()
    {
        var code = await Customer(10);
        var input = new QuoteInput(code, [new(1, 50m)]);
        Assert.Equal(HttpStatusCode.Conflict, (await sql.Client.PostAsJsonAsync("/teklifler", input)).StatusCode);
        await using var db = await sql.Open();
        Assert.Equal(0, await db.ExecuteScalarAsync<int>("SELECT COUNT(*) FROM dbo.Teklifler WHERE CariKod=@code;", new { code }));
        var response = await sql.Client.PostAsJsonAsync("/teklifler", input with { KrediLimitiAsiminiOnayla = true });
        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        Assert.Equal(60m, (await response.Content.ReadFromJsonAsync<Quote>())!.YeniBakiye);
    }
    [SqlFact]
    public async Task Missing_customer_has_an_actionable_not_found_response()
     => Assert.Equal(HttpStatusCode.NotFound, (await sql.Client.PostAsJsonAsync("/teklifler", new QuoteInput("MISSING", [new(1, 1)]))).StatusCode);

    [SqlFact]
    public async Task Balance_write_failure_rolls_back_the_inserted_quote()
    {
        var code = await Customer(1000);
        await using var db = await sql.Open();
        // This trigger exists only in the randomly named disposable test database.
        // The interpolated code is generated by Customer(), never supplied by a user.
        await db.ExecuteAsync($"""
            CREATE TRIGGER dbo.Test_BlockBalanceUpdate ON dbo.Cariler AFTER UPDATE AS
            BEGIN
                IF EXISTS (SELECT 1 FROM inserted WHERE CariKod=N'{code}')
                    THROW 51001, 'Intentional test-only balance write failure', 1;
            END;
            """);
        try
        {
            using var response = await sql.Client.PostAsJsonAsync("/teklifler",
                new QuoteInput(code, [new(1, 50m)]));
            Assert.Equal(HttpStatusCode.InternalServerError, response.StatusCode);
            Assert.Equal(0, await db.ExecuteScalarAsync<int>(
                "SELECT COUNT(*) FROM dbo.Teklifler WHERE CariKod=@code;", new { code }));
            Assert.Equal(0m, await db.ExecuteScalarAsync<decimal>(
                "SELECT Bakiye FROM dbo.Cariler WHERE CariKod=@code;", new { code }));
        }
        finally
        {
            await db.ExecuteAsync("DROP TRIGGER IF EXISTS dbo.Test_BlockBalanceUpdate;");
        }
    }
}
